const MISSING = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

export type Align = "left" | "center" | "right";

export function textWidth(str: string): number {
  return str.length * ADVANCE - 1;
}

/**
 * Draw `str` at pixel (x, y). With `shadow` set, a 1px offset copy is drawn
 * underneath first for legibility over the sky.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  color = "#fff",
  align: Align = "left",
  shadow: string | null = "rgba(0,0,0,0.85)",
): void {
  const s = str.toUpperCase();
  let ox = Math.round(x);
  if (align === "center") ox -= Math.round(textWidth(s) / 2);
  else if (align === "right") ox -= textWidth(s);
  const oy = Math.round(y);

  if (shadow) blit(ctx, s, ox + 1, oy + 1, shadow);
  blit(ctx, s, ox, oy, color);
}

function blit(
  ctx: CanvasRenderingContext2D,
  s: string,
  ox: number,
  oy: number,
  color: string,
): void {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const rows = GLYPHS[s[i]] ?? MISSING;
    const gx = ox + i * ADVANCE;
    for (let r = 0; r < H; r++) {
      const row = rows[r];
      for (let c = 0; c < W; c++) {
        if (row[c] === "#") ctx.fillRect(gx + c, oy + r, 1, 1);
      }
    }
  }
}
